"""DNS allowlist for the sandbox network (dnsmasq config generated from the proxy config).

Only names the proxy would let through anyway (secret hosts, ``intercept`` and
``tunnel``) resolve; everything else is refused. That closes DNS as an
exfiltration channel (data hidden in query names sent to an attacker's domain).
"""
from __future__ import annotations

from .config import Config

_WILD = set("*?[")


def allowed_domains(cfg: Config) -> tuple[list[str], bool]:
    """(domains, allow_all). Each domain also covers its subdomains, as in dnsmasq."""
    if cfg.default == "intercept":
        return [], True  # every host is allowed through the proxy, so every name must resolve
    patterns = [p for s in cfg.secrets for p in s.hosts.patterns]
    patterns += cfg.intercept.patterns + cfg.tunnel.patterns
    found: set[str] = set()
    for p in patterns:
        labels = p.lower().rstrip(".").split(".")
        last_wild = max((i for i, l in enumerate(labels) if _WILD & set(l)), default=-1)
        suffix = labels[last_wild + 1:]
        if not suffix:
            return [], True  # a bare "*" pattern allows everything
        found.add(".".join(suffix))
    minimal = sorted(d for d in found if not any(d != o and d.endswith("." + o) for o in found))
    return minimal, False


def dnsmasq_config(cfg: Config, upstreams: list[str], interface: str | None = None,
                   allow_all: bool = False) -> str:
    if not upstreams:
        raise ValueError("at least one upstream resolver is required")
    domains, everything = allowed_domains(cfg)
    everything = everything or allow_all
    lines = ["# generated by: secretproxy dns-config  (regenerate after changing config.yaml)",
             "no-resolv", "no-hosts", "bind-interfaces"]
    if interface:
        lines += [f"interface={interface}", "except-interface=lo"]
    if everything:
        lines.append("# allow-all: every name is forwarded")
        lines += [f"server={u}" for u in upstreams]
    else:
        lines.append("# allowlist: only these domains and their subdomains resolve, the rest is refused")
        lines += [f"server=/{d}/{u}" for d in domains for u in upstreams]
    return "\n".join(lines) + "\n"
